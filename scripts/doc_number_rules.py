#!/usr/bin/env python3
"""Переменные №1 (doc_no) и №2 (ref_no): правило записи, генерация, чистка списков.

Что выявлено по 85 реальным банковским справкам архива:
  * №1 (строка «No », напр. ae32271197) — две строчные латинские буквы + восемь цифр;
  * №2 (строка «Ref. », напр. B19289961ADL) — одна заглавная буква + восемь цифр + три заглавные.

Порядок заполнения: данные клиента → значение из его реальной справки на Google Drive →
генерация от даты формирования документа и имени с фамилией клиента (уникально для клиента
и дня, при повторной сборке не меняется). Кнопка 🎲 рядом с полем даёт новый уникальный
номер того же формата. Список прошлых значений у этих двух полей отключён.
"""
import sqlite3

DB = '/opt/wolf_v2/data/wolf.db'

NOTE_DOC_NO = (
    'Номер документа из строки «No » в справке банка. Формат в реальных справках: '
    'две строчные латинские буквы + восемь цифр (пример: ae32271197). '
    'Порядок заполнения: (1) если у клиента на Google Drive есть банковская справка — номер берётся оттуда; '
    '(2) если её нет — система генерирует номер от даты формирования документа и имени с фамилией клиента: '
    'значение уникально для каждого клиента и дня, при повторной сборке документа остаётся тем же; '
    '(3) кнопка 🎲 рядом с полем создаёт новый уникальный номер того же формата. '
    'Выбор из списка прошлых значений для этого поля отключён.'
)

NOTE_REF_NO = (
    'Исходящий номер из строки «Ref. » в справке банка. Формат в реальных справках: '
    'одна заглавная латинская буква + восемь цифр + три заглавные буквы (пример: B19289961ADL). '
    'Порядок заполнения: (1) значение из банковской справки клиента на Google Drive; '
    '(2) если справки нет — генерация от даты формирования документа и имени с фамилией клиента: '
    'уникально для каждого клиента и дня, при повторной сборке не меняется; '
    '(3) кнопка 🎲 рядом с полем даёт новый уникальный номер того же формата. '
    'Выбор из списка прошлых значений для этого поля отключён.'
)

conn = sqlite3.connect(DB)
n_var = conn.execute(
    "UPDATE template_variables SET rule_note=?, examples_json='[]', default_value='' "
    "WHERE name='doc_no'", (NOTE_DOC_NO,)).rowcount
n_ref = conn.execute(
    "UPDATE template_variables SET rule_note=?, examples_json='[]', default_value='' "
    "WHERE name='ref_no'", (NOTE_REF_NO,)).rowcount
n_hist = conn.execute(
    "DELETE FROM variable_value_history WHERE variable_name IN ('doc_no','ref_no')").rowcount
conn.commit()
conn.close()
print(f'правило + чистка: doc_no — {n_var} шаблонов, ref_no — {n_ref} шаблонов, '
      f'удалено подсказок из истории: {n_hist}')
