#!/bin/sh
# Распознавание документов не должно тормозить интерфейс: запускаем tesseract
# с пониженным приоритетом и одним потоком. На сервере мало ядер, и OCR в
# полную силу забирает ядро целиком — администратор в это время ждёт страницу.
OMP_THREAD_LIMIT=1
export OMP_THREAD_LIMIT
exec /usr/bin/nice -n 15 /usr/bin/tesseract "$@"
